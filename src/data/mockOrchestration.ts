import type {
  BookingRecord,
  DecisionScore,
  DeliveryEvent,
  DeliveryRequest,
  OrchestrationDecision,
  OrchestrationRecord,
  ScoreFactorKey,
  ServiceEvaluation,
} from "./orchestrationTypes";
import { SCORE_FACTOR_WEIGHTS } from "./orchestrationTypes";

function buildDecisionScore(
  scores: Record<ScoreFactorKey, number>,
): DecisionScore {
  const factors = {} as DecisionScore["factors"];
  let totalScore = 0;

  (Object.keys(SCORE_FACTOR_WEIGHTS) as ScoreFactorKey[]).forEach((key) => {
    const weight = SCORE_FACTOR_WEIGHTS[key];
    const score = scores[key];
    const weightedScore = Math.round((score * weight) / 100 * 10) / 10;
    factors[key] = { weight, score, weightedScore };
    totalScore += weightedScore;
  });

  return {
    factors,
    totalScore: Math.round(totalScore * 10) / 10,
  };
}

function addMs(iso: string, ms: number): string {
  return new Date(new Date(iso).getTime() + ms).toISOString();
}

type EventConfig = {
  orchestrationStartMs: number;
  orchestrationDurationMs: number;
  bookingDelayMs: number;
  bookingResponseMs: number;
  bookingStatus: "confirmed" | "failed" | "cancelled";
};

function buildEvents(
  deliveryId: string,
  createdAt: string,
  status: DeliveryRequest["status"],
  config: EventConfig,
): DeliveryEvent[] {
  const {
    orchestrationStartMs,
    orchestrationDurationMs,
    bookingDelayMs,
    bookingResponseMs,
    bookingStatus,
  } = config;

  const orchCompletedAt = addMs(
    createdAt,
    orchestrationStartMs + orchestrationDurationMs,
  );
  const bookingRequestedAt = addMs(orchCompletedAt, bookingDelayMs);
  const bookingResolvedAt = addMs(bookingRequestedAt, bookingResponseMs);

  const events: DeliveryEvent[] = [
    {
      id: `${deliveryId}-evt-1`,
      deliveryId,
      type: "created",
      timestamp: createdAt,
      description: "Delivery request received from customer.",
    },
    {
      id: `${deliveryId}-evt-2`,
      deliveryId,
      type: "orchestration_started",
      timestamp: addMs(createdAt, orchestrationStartMs),
      description: "Dutt orchestration engine started evaluating delivery services.",
    },
    {
      id: `${deliveryId}-evt-3`,
      deliveryId,
      type: "orchestration_completed",
      timestamp: orchCompletedAt,
      description: "Orchestration completed and best option selected.",
    },
    {
      id: `${deliveryId}-evt-4`,
      deliveryId,
      type: "booking_requested",
      timestamp: bookingRequestedAt,
      description: "Booking request sent to selected service.",
    },
  ];

  if (bookingStatus === "confirmed") {
    events.push({
      id: `${deliveryId}-evt-5`,
      deliveryId,
      type: "booking_confirmed",
      timestamp: bookingResolvedAt,
      description: "Booking confirmed by selected service.",
    });

    if (status !== "cancelled" && status !== "failed") {
      events.push(
        {
          id: `${deliveryId}-evt-6`,
          deliveryId,
          type: "driver_assigned",
          timestamp: addMs(bookingResolvedAt, 180_000),
          description: "Driver assigned for pickup.",
        },
        {
          id: `${deliveryId}-evt-7`,
          deliveryId,
          type: "picked_up",
          timestamp: addMs(bookingResolvedAt, 1_800_000),
          description: "Package picked up from origin.",
        },
      );
    }

    if (status === "in_transit" || status === "delivered") {
      events.push({
        id: `${deliveryId}-evt-8`,
        deliveryId,
        type: "in_transit",
        timestamp: addMs(bookingResolvedAt, 2_100_000),
        description: "Package in transit to destination.",
      });
    }

    if (status === "delivered") {
      events.push({
        id: `${deliveryId}-evt-9`,
        deliveryId,
        type: "delivered",
        timestamp: addMs(bookingResolvedAt, 4_200_000),
        description: "Package delivered successfully.",
      });
    }

    if (status === "cancelled") {
      events.push({
        id: `${deliveryId}-evt-8`,
        deliveryId,
        type: "cancelled",
        timestamp: addMs(bookingResolvedAt, 900_000),
        description: "Delivery cancelled after booking confirmation.",
      });
    }
  }

  if (bookingStatus === "failed") {
    events.push({
      id: `${deliveryId}-evt-5`,
      deliveryId,
      type: "failed",
      timestamp: bookingResolvedAt,
      description: "Booking failed with selected service.",
    });
  }

  return events;
}

function buildDecision(
  deliveryId: string,
  createdAt: string,
  durationMs: number,
  evaluations: ServiceEvaluation[],
  selectedServiceId: string,
  selectedServiceName: string,
  selectionReason: string,
  winnerScores: Record<ScoreFactorKey, number>,
): OrchestrationDecision {
  const startedAt = addMs(createdAt, 400);
  return {
    deliveryId,
    orchestrationId: `ORCH-${deliveryId.replace("DUTT-", "")}`,
    startedAt,
    completedAt: addMs(startedAt, durationMs),
    durationMs,
    servicesEvaluated: evaluations.length,
    availableOptions: evaluations.filter((e) => e.availability).length,
    selectedServiceId,
    selectedServiceName,
    selectionReason,
    decisionScore: buildDecisionScore(winnerScores),
    evaluations,
  };
}

function createRecord(
  deliveryRequest: DeliveryRequest,
  evaluations: ServiceEvaluation[],
  durationMs: number,
  selectedServiceId: string,
  selectionReason: string,
  winnerScores: Record<ScoreFactorKey, number>,
  booking: BookingRecord,
  eventConfig: EventConfig,
): OrchestrationRecord {
  const selected = evaluations.find((e) => e.serviceId === selectedServiceId);
  const decision = buildDecision(
    deliveryRequest.deliveryId,
    deliveryRequest.createdAt,
    durationMs,
    evaluations,
    selectedServiceId,
    selected?.serviceName ?? selectedServiceId,
    selectionReason,
    winnerScores,
  );

  return {
    deliveryRequest,
    evaluations,
    decision,
    booking,
    events: buildEvents(
      deliveryRequest.deliveryId,
      deliveryRequest.createdAt,
      deliveryRequest.status,
      eventConfig,
    ),
  };
}

